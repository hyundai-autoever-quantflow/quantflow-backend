-- positions
CREATE TABLE positions (
    position_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    stock_id BIGINT NOT NULL,
    quantity NUMERIC(20,0) NOT NULL,
    average_entry_price NUMERIC(20,4) NOT NULL,
    gross_realized_pnl_krw NUMERIC(20,0) DEFAULT 0 NOT NULL,
    status VARCHAR(20) DEFAULT 'OPEN' NOT NULL CHECK ((status IN ('OPEN','CLOSED'))),
    opened_at TIMESTAMP(6) NOT NULL,
    closed_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    connection_id BIGINT NOT NULL,
    settings_id BIGINT NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (position_id),
    CONSTRAINT uk_positions_1 UNIQUE (position_id, analysis_id, stock_id, connection_id, user_id, settings_id),
    CONSTRAINT ck_positions_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_positions_entry_price CHECK (average_entry_price > 0)
);

-- orders
CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    position_id BIGINT,
    stock_id BIGINT NOT NULL,
    client_order_key VARCHAR(150) NOT NULL,
    broker_order_no VARCHAR(100),
    broker_order_date DATE,
    side VARCHAR(4) NOT NULL CHECK ((side IN ('BUY','SELL'))),
    order_type VARCHAR(10) NOT NULL CHECK ((order_type IN ('LIMIT','MARKET'))),
    quantity NUMERIC(20,0) NOT NULL,
    limit_price NUMERIC(20,4),
    filled_quantity NUMERIC(20,0) DEFAULT 0 NOT NULL,
    status VARCHAR(30) DEFAULT 'CREATED' NOT NULL CHECK ((status IN ('CREATED','SUBMITTING','ACCEPTED','PARTIALLY_FILLED','FILLED','CANCEL_PENDING','CANCELED','REJECTED','UNKNOWN'))),
    trigger_type VARCHAR(30) NOT NULL CHECK ((trigger_type IN ('ENTRY_RULE','TAKE_PROFIT','STOP_LOSS','TIME_EXIT','SESSION_EXIT','RISK_EXIT'))),
    decision_snapshot JSONB NOT NULL,
    rejection_reason TEXT,
    user_id BIGINT NOT NULL,
    connection_id BIGINT NOT NULL,
    settings_id BIGINT NOT NULL,
    exchange_route VARCHAR(10) DEFAULT 'KRX' NOT NULL,
    reference_price NUMERIC(20,4) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    broker_org_no VARCHAR(100),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (order_id),
    CONSTRAINT uk_orders_1 UNIQUE (client_order_key),
    CONSTRAINT uk_orders_2 UNIQUE (connection_id, broker_order_date, broker_order_no),
    CONSTRAINT ck_orders_quantity CHECK (quantity > 0),
    CONSTRAINT ck_orders_filled_quantity CHECK (filled_quantity >= 0 AND filled_quantity <= quantity),
    CONSTRAINT ck_orders_limit_price CHECK ((order_type = 'LIMIT' AND limit_price IS NOT NULL AND limit_price > 0) OR (order_type = 'MARKET' AND limit_price IS NULL)),
    CONSTRAINT ck_orders_reference_price CHECK (reference_price > 0),
    CONSTRAINT ck_orders_sell_position CHECK (side <> 'SELL' OR position_id IS NOT NULL),
    CONSTRAINT ck_orders_decision_snapshot CHECK (jsonb_typeof(decision_snapshot) = 'object')
);

-- executions
CREATE TABLE executions (
    execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    execution_key VARCHAR(200) NOT NULL,
    quantity NUMERIC(20,0) NOT NULL,
    price NUMERIC(20,4) NOT NULL,
    fee_krw NUMERIC(20,0),
    tax_krw NUMERIC(20,0),
    cost_status VARCHAR(20) DEFAULT 'UNKNOWN' NOT NULL CHECK ((cost_status IN ('UNKNOWN','ESTIMATED','FINAL'))),
    executed_at TIMESTAMP(6) NOT NULL,
    received_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (execution_id),
    CONSTRAINT uk_executions_1 UNIQUE (order_id, execution_key),
    CONSTRAINT ck_executions_quantity CHECK (quantity > 0),
    CONSTRAINT ck_executions_price CHECK (price > 0),
    CONSTRAINT ck_executions_costs CHECK ((fee_krw IS NULL OR fee_krw >= 0) AND (tax_krw IS NULL OR tax_krw >= 0))
);

-- order_events
CREATE TABLE order_events (
    order_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    source_event_key VARCHAR(200) NOT NULL,
    event_type VARCHAR(50) NOT NULL CHECK ((event_type IN ('SUBMIT','ACK','FILL','CANCEL_REQUEST','CANCEL_ACK','RECONCILE'))),
    previous_status VARCHAR(30) CHECK ((previous_status IN ('CREATED','SUBMITTING','ACCEPTED','PARTIALLY_FILLED','FILLED','CANCEL_PENDING','CANCELED','REJECTED','UNKNOWN'))),
    new_status VARCHAR(30) NOT NULL CHECK ((new_status IN ('CREATED','SUBMITTING','ACCEPTED','PARTIALLY_FILLED','FILLED','CANCEL_PENDING','CANCELED','REJECTED','UNKNOWN'))),
    sanitized_payload JSONB NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    received_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (order_event_id),
    CONSTRAINT uk_order_events_1 UNIQUE (order_id, source_event_key),
    CONSTRAINT ck_order_events_sanitized_payload CHECK (jsonb_typeof(sanitized_payload) = 'object')
);

