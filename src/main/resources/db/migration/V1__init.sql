    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (settings_id),
    CONSTRAINT uk_trading_settings_1 UNIQUE (user_id, version),
    CONSTRAINT uk_trading_settings_2 UNIQUE (settings_id, user_id),
    CONSTRAINT uk_trading_settings_3 UNIQUE (user_id, request_key),
    CONSTRAINT ck_trading_settings_version CHECK (version > 0),
    CONSTRAINT ck_trading_settings_entry_budget CHECK (entry_budget_krw > 0),
    CONSTRAINT ck_trading_settings_max_buys CHECK (max_buys_per_day > 0),
    CONSTRAINT ck_trading_settings_take_profit CHECK (take_profit_pct > 0),
    CONSTRAINT ck_trading_settings_stop_loss CHECK (stop_loss_pct < 0),
    CONSTRAINT ck_trading_settings_holding_minutes CHECK (max_holding_minutes > 0),
    CONSTRAINT ck_trading_settings_loss_limit CHECK (daily_loss_limit_krw > 0),
    CONSTRAINT ck_trading_settings_risk_limits CHECK (jsonb_typeof(risk_limits) = 'object')
);

-- automations
CREATE TABLE automations (
    automation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    connection_id BIGINT NOT NULL,
    settings_id BIGINT NOT NULL,
    desired_state VARCHAR(20) DEFAULT 'STOPPED' NOT NULL CHECK ((desired_state IN ('RUNNING','STOPPED'))),
    runtime_state VARCHAR(20) DEFAULT 'IDLE' NOT NULL CHECK ((runtime_state IN ('IDLE','SCHEDULED','ANALYZING','WATCHING','HOLDING','STOPPING','BLOCKED'))),
    kill_switch_active BOOLEAN DEFAULT false NOT NULL,
    block_reason VARCHAR(100),
    next_run_at TIMESTAMP(6),
    control_receipts JSONB DEFAULT '[]'::jsonb NOT NULL,
    resource_version BIGINT DEFAULT 0 NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (automation_id),
    CONSTRAINT uk_automations_1 UNIQUE (connection_id),
    CONSTRAINT uk_automations_2 UNIQUE (automation_id, user_id),
    CONSTRAINT ck_automations_resource_version CHECK (resource_version >= 0),
    CONSTRAINT ck_automations_control_receipts CHECK (jsonb_typeof(control_receipts) = 'array')
);

-- daily_risk_states
CREATE TABLE daily_risk_states (
    risk_state_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    connection_id BIGINT NOT NULL,
    trading_date DATE NOT NULL,
    settings_id BIGINT NOT NULL,
    starting_equity_krw NUMERIC(20,0) NOT NULL,
    current_equity_krw NUMERIC(20,0),
    net_cash_flow_krw NUMERIC(20,0),
    daily_pnl_krw NUMERIC(20,0),
    daily_loss_limit_krw NUMERIC(20,0) NOT NULL,
    consecutive_losses INTEGER DEFAULT 0 NOT NULL,
    buy_count INTEGER DEFAULT 0 NOT NULL,
    hard_stop_active BOOLEAN DEFAULT false NOT NULL,
    hard_stop_reason VARCHAR(100),
    baseline_at TIMESTAMP(6) NOT NULL,
    as_of TIMESTAMP(6) NOT NULL,
    resource_version BIGINT DEFAULT 0 NOT NULL,
    PRIMARY KEY (risk_state_id),
    CONSTRAINT uk_daily_risk_states_1 UNIQUE (connection_id, trading_date),
    CONSTRAINT ck_daily_risk_states_equity CHECK (starting_equity_krw >= 0 AND (current_equity_krw IS NULL OR current_equity_krw >= 0)),
    CONSTRAINT ck_daily_risk_states_loss_limit CHECK (daily_loss_limit_krw > 0),
    CONSTRAINT ck_daily_risk_states_counts CHECK (buy_count >= 0 AND consecutive_losses >= 0),
    CONSTRAINT ck_daily_risk_states_resource_version CHECK (resource_version >= 0)
);

