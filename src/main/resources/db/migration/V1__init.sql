-- QUANTFLOW initial PostgreSQL schema (14 entities).
-- Uses current JPA mappings: users.member_id is the user primary key.
-- LocalDateTime maps to TIMESTAMP(6) WITHOUT TIME ZONE, not TIMESTAMPTZ.
-- Run against an existing empty database; database creation is outside Flyway.
-- Defaults initialize inserts only; application auditing maintains update times.

-- users
CREATE TABLE users (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    social_provider VARCHAR(255) CHECK ((social_provider IN ('KAKAO','GOOGLE','NAVER'))),
    provider_id VARCHAR(255),
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(50) UNIQUE,
    preferred_categories JSONB DEFAULT '[]'::jsonb NOT NULL,
    preferences_version INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (member_id),
    CONSTRAINT ck_users_preferences_version CHECK (preferences_version >= 0),
    CONSTRAINT ck_users_preferred_categories CHECK (jsonb_typeof(preferred_categories) = 'array')
);

-- broker_connections
CREATE TABLE broker_connections (
    connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    broker VARCHAR(20) NOT NULL CHECK ((broker IN ('KIS'))),
    account_fingerprint VARCHAR(128) NOT NULL,
    account_number_masked VARCHAR(50) NOT NULL,
    environment VARCHAR(20) NOT NULL CHECK ((environment IN ('BROKER_PAPER','LIVE'))),
    status VARCHAR(30) DEFAULT 'VERIFYING' NOT NULL CHECK ((status IN ('VERIFYING','CONNECTED','RECONNECT_REQUIRED','DISCONNECTING','DISCONNECTED','FAILED'))),
    credential_ref TEXT,
    permissions JSONB DEFAULT '{}'::jsonb NOT NULL,
    reconciliation_status VARCHAR(20) DEFAULT 'PENDING' NOT NULL CHECK ((reconciliation_status IN ('PENDING','MATCHED','MISMATCH','FAILED'))),
    last_reconciled_at TIMESTAMP(6),
    last_verified_at TIMESTAMP(6),
    last_error_code VARCHAR(80),
    request_key VARCHAR(150) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    request_receipts JSONB DEFAULT '[]'::jsonb NOT NULL,
    resource_version BIGINT DEFAULT 0 NOT NULL,
    disconnected_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (connection_id),
    CONSTRAINT uk_broker_connections_connection_user UNIQUE (connection_id, user_id),
    CONSTRAINT uk_broker_connections_user_request UNIQUE (user_id, request_key),
    CONSTRAINT ck_broker_connections_resource_version CHECK (resource_version >= 0),
    CONSTRAINT ck_broker_connections_permissions CHECK (jsonb_typeof(permissions) = 'object'),
    CONSTRAINT ck_broker_connections_request_receipts CHECK (jsonb_typeof(request_receipts) = 'array')
);

-- stocks
CREATE TABLE stocks (
    stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    market VARCHAR(20) NOT NULL,
    symbol VARCHAR(20) NOT NULL,
    company_name VARCHAR(200) NOT NULL,
    dart_corp_code VARCHAR(20),
    is_tradable BOOLEAN DEFAULT false NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    category_codes JSONB DEFAULT '[]'::jsonb NOT NULL,
    instrument_type VARCHAR(30) NOT NULL,
    market_flags JSONB DEFAULT '{}'::jsonb NOT NULL,
    market_status_at TIMESTAMP(6),
    PRIMARY KEY (stock_id),
    CONSTRAINT uk_stocks_1 UNIQUE (market, symbol),
    CONSTRAINT ck_stocks_category_codes CHECK (jsonb_typeof(category_codes) = 'array'),
    CONSTRAINT ck_stocks_market_flags CHECK (jsonb_typeof(market_flags) = 'object')
);

-- trading_settings
CREATE TABLE trading_settings (
    settings_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
